# Cap on how many per-chunk loss samples we echo back for the surface's
# streaming loss-curve animation (keeps payload bounded for large num_chunks).
_MAX_CURVE_SAMPLES = 96

# Fixed toy-model dimensions (architecture constants, not data-driven):
_D_MODEL = 8      # hidden width of the toy block
_D_FF    = 16     # feed-forward width of the toy block
_VOCAB   = 16     # synthetic vocabulary size (16 symbols)

# STRICTLY-CAUSAL 1-D convolution kernel used to build the NTP-aligned target.
# Taps are applied to inputs at offsets +0, -1, -2 relative to position t — they
# reach STRICTLY into the PAST (and present). No positive (future) offset exists,
# so no future token can leak into a target. The causality guard below asserts
# this explicitly.
_CAUSAL_KERNEL = [0.6, 0.3, 0.1]          # tap for offset 0, -1, -2
_CAUSAL_OFFSETS = [0, -1, -2]             # <= 0 only  ==>  no future leakage


# ---------------------------------------------------------------------------
# Pure-stdlib deterministic LCG PRNG (no numpy, no stdlib `random`) — same
# generator family used across the SZL organ endpoints for reproducibility.
# ---------------------------------------------------------------------------
def _lcg(seed: int):
    s = (int(seed) ^ 0x9E3779B9) & 0xFFFFFFFF
    while True:
        s = (1664525 * s + 1013904223) & 0xFFFFFFFF
        yield s / 0xFFFFFFFF


# ---------------------------------------------------------------------------
# Small explicit linear-algebra helpers (pure stdlib float lists)
# ---------------------------------------------------------------------------
def _matvec(M, x):
    """M (rows x cols) times vector x (cols) -> vector (rows)."""
    return [sum(M[r][c] * x[c] for c in range(len(x))) for r in range(len(M))]


def _act(v):
    """Elementwise SiLU-like smooth activation (pure stdlib, bounded)."""
    out = []
    for z in v:
        # numerically-safe logistic gate * z  (SiLU = z * sigmoid(z))
        if z >= 0:
            s = 1.0 / (1.0 + _exp(-z))
        else:
            e = _exp(z)
            s = e / (1.0 + e)
        out.append(z * s)
    return out


def _exp(x):
    """Bounded exp via math without importing random/numpy."""
    import math
    # clamp to avoid overflow on extreme toy values
    if x > 60.0:
        x = 60.0
    elif x < -60.0:
        x = -60.0
    return math.exp(x)


