def _causal_guard_ok() -> bool:
    """Explicit causality guard: the NTP-target convolution may ONLY read the
    present and past. Assert that every kernel offset is <= 0 (no future tap)."""
    return all(off <= 0 for off in _CAUSAL_OFFSETS)


def _causal_target(embeds, t, d_model):
    """Build the NTP-aligned target at position t via a STRICTLY-CAUSAL 1-D
    convolution over the input embeddings. Position t reads only t, t-1, t-2
    (offsets <= 0) — a future token can NEVER contribute. Positions before the
    start are zero-padded (causal left-padding)."""
    tgt = [0.0] * d_model
    for tap, off in zip(_CAUSAL_KERNEL, _CAUSAL_OFFSETS):
        src = t + off                       # off <= 0  ==>  src <= t  (past/present only)
        if src < 0:
            continue                        # causal zero-padding on the left
        e = embeds[src]
        for c in range(d_model):
            tgt[c] += tap * e[c]
    return tgt


def _forward(x, W_up, W_gate, W_down):
    """Gated-MLP block: hidden = W_down · ( act(W_gate·x) ⊙ (W_up·x) ).

    Returns (hidden, up, gated_act, gate_pre) so the analytic W_down gradient
    can be formed without any autograd. Shapes:
      x        : d_model
      W_up     : d_ff  x d_model   (frozen slow weight)
      W_gate   : d_ff  x d_model   (frozen slow weight)
      W_down   : d_model x d_ff    (FAST weight — the one that adapts)
    """
    up   = _matvec(W_up, x)                 # d_ff
    gpre = _matvec(W_gate, x)               # d_ff
    ga   = _act(gpre)                       # d_ff  (activation on the gate)
    inner = [ga[i] * up[i] for i in range(len(up))]   # d_ff  (gated)
    hidden = _matvec(W_down, inner)         # d_model
    return hidden, inner


def _sq_loss(hidden, target):
    """Mean squared next-token-aligned error over d_model."""
    n = len(hidden)
    return sum((hidden[i] - target[i]) ** 2 for i in range(n)) / max(n, 1)


def _inplacettt_snapshot(seed: int = 42, chunk_size: int = 16,
                         learning_rate: float = 0.2,
                         num_chunks: int = 24) -> dict:
    """
    Stream num_chunks * chunk_size synthetic tokens through a toy single-MLP
    block twice: once ADAPTING W_down per chunk (fast weights) and once with
    W_down FROZEN (control). Report the per-chunk running next-token loss for
    both, plus start/end deltas.

    Pure stdlib; deterministic — same (seed, chunk_size, learning_rate,
    num_chunks) -> identical snapshot, every time.
    """
    rng = _lcg(seed)
    d_model, d_ff, vocab = _D_MODEL, _D_FF, _VOCAB

    # ---- explicit, deterministically-seeded toy weights -------------------
    def _mat(rows, cols, scale):
        return [[(next(rng) * 2.0 - 1.0) * scale for _ in range(cols)]
                for _ in range(rows)]

    W_up   = _mat(d_ff, d_model, 0.5)        # FROZEN slow weight
    W_gate = _mat(d_ff, d_model, 0.5)        # FROZEN slow weight
    W_down_init = _mat(d_model, d_ff, 0.4)   # FAST weight (adapts)

    # ---- deterministic per-symbol embedding table ------------------------
    emb_table = [[(next(rng) * 2.0 - 1.0) for _ in range(d_model)]
                 for _ in range(vocab)]

    # ---- synthetic token stream: copy-with-shift over a 16-symbol vocab --
    # fixed rule => strong next-token structure the fast weights can exploit.
    # We make the stream PERIODIC with period == chunk_size so every chunk sees
    # the SAME tokens in the SAME order. This makes the frozen-W_down control's
    # per-chunk loss EXACTLY constant (an honest FLAT baseline), while the
    # adapting run's loss FALLS as W_down learns the repeated pattern.
    n_tokens = chunk_size * num_chunks
    shift = 3
    # build one period of length chunk_size via the copy-with-shift rule, then
    # tile it across all chunks.
    cur = int(next(rng) * vocab) % vocab
    period = []
    for _ in range(chunk_size):
        period.append(cur)
        cur = (cur + shift) % vocab          # deterministic copy-with-shift rule
    stream = [period[i % chunk_size] for i in range(n_tokens)]
    embeds = [emb_table[tok] for tok in stream]

    # ---- causality guard (explicit) --------------------------------------
    guard_ok = _causal_guard_ok()
    assert guard_ok, "CAUSALITY VIOLATION: NTP target kernel has a future tap"

    freeze_up = True
    freeze_gate = True

    def _run(adapt: bool):
        """Run the whole stream in chunks. If adapt, take ONE analytic GD step
        on W_down ONLY per chunk; else hold W_down frozen (control)."""
        # deep copy the fast matrix so the two runs are independent
        W_down = [row[:] for row in W_down_init]
        per_chunk_loss = []
        total_delta_l1 = 0.0

        for ci in range(num_chunks):
            start = ci * chunk_size
            chunk_loss_sum = 0.0
            # accumulate the analytic gradient of the squared NTP loss wrt
            # W_down over the whole chunk (chunk-parallel update).
            grad = [[0.0] * d_ff for _ in range(d_model)]

            for k in range(chunk_size):
                t = start + k
                x = embeds[t]
                target = _causal_target(embeds, t, d_model)   # causal, past-only
                hidden, inner = _forward(x, W_up, W_gate, W_down)
                chunk_loss_sum += _sq_loss(hidden, target)

                # dL/dhidden = 2/d_model * (hidden - target)
                # hidden = W_down · inner  ==>  dL/dW_down[i][j] = dL/dhidden[i]*inner[j]
                for i in range(d_model):
                    dh = (2.0 / d_model) * (hidden[i] - target[i])
                    row = grad[i]
                    for j in range(d_ff):
                        row[j] += dh * inner[j]

            per_chunk_loss.append(chunk_loss_sum / max(chunk_size, 1))

            if adapt:
                # ONE gradient-descent step on W_down ONLY (W_up/W_gate frozen).
                inv = 1.0 / max(chunk_size, 1)
                for i in range(d_model):
                    for j in range(d_ff):
                        step = learning_rate * grad[i][j] * inv
                        W_down[i][j] -= step
                        total_delta_l1 += abs(step)

        return per_chunk_loss, total_delta_l1

    adapt_loss, delta_l1 = _run(adapt=True)
    frozen_loss, _ = _run(adapt=False)

    # ---- assemble a capped, aligned loss curve for the surface -----------
    curve = []
    step = max(1, num_chunks // _MAX_CURVE_SAMPLES) if num_chunks > _MAX_CURVE_SAMPLES else 1
    for ci in range(0, num_chunks, step):
        if len(curve) >= _MAX_CURVE_SAMPLES:
            break
        curve.append({
            "chunk": ci,
            "adapt_loss": round(adapt_loss[ci], 6),
            "frozen_loss": round(frozen_loss[ci], 6),
        })

    # Use the FIRST FULLY-PERIODIC chunk as the 'start' reference. Chunk 0 has
    # causal left-padding (positions 0,1 lack a full past), so from chunk 1
    # onward every chunk sees an identical periodic window — making the frozen
    # control EXACTLY flat and the adapting run's drop an honest signal.
    ref = 1 if num_chunks > 1 else 0
    adapt_start, adapt_end = adapt_loss[ref], adapt_loss[-1]
    frozen_start, frozen_end = frozen_loss[ref], frozen_loss[-1]

    payload = {
        "d_model": d_model,
        "d_ff": d_ff,
        "vocab": vocab,
        "chunk_size": chunk_size,
        "num_chunks": num_chunks,
        "learning_rate": round(learning_rate, 6),
        "freeze_up": freeze_up,
        "freeze_gate": freeze_gate,
        "fast_matrix": "W_down",
        "causal_kernel": list(_CAUSAL_KERNEL),
        "causal_offsets": list(_CAUSAL_OFFSETS),
        "causal_guard_ok": bool(guard_ok),
        "adapt_loss_start": round(adapt_start, 6),
        "adapt_loss_end": round(adapt_end, 6),
        "frozen_loss_start": round(frozen_start, 6),
        "frozen_loss_end": round(frozen_end, 6),
        "adapt_loss_drop": round(adapt_start - adapt_end, 6),
        "frozen_loss_drop": round(frozen_start - frozen_end, 6),
        "improvement": round(frozen_end - adapt_end, 6),
        "loss_curve": curve,
        "w_down_delta_norm": round(delta_l1, 6),
    }
    return payload


