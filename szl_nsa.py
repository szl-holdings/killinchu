def register(app, ns: str = "killinchu") -> list:
    """Wire nsa routes under /api/<ns>/v1/nsa/* (and bare /v1/nsa/* so the
    generic Node proxy at /api/killinchu/{path:path} -> Node /v1/* maps too).
    Additive; uses add_api_route when present (FastAPI) with a manual
    Starlette Route fallback for bare ASGI apps — same pattern as the
    specdec/specdecode siblings."""
    base = f"/api/{ns}/v1/nsa"
    handlers = [
        (f"{base}/health", _h_health, ["GET"]),
        (f"{base}/simulate", _h_simulate, ["GET", "POST"]),
        ("/v1/nsa/health", _h_health, ["GET"]),
        ("/v1/nsa/simulate", _h_simulate, ["GET", "POST"]),
    ]
    add_api_route = getattr(app, "add_api_route", None)
    for path, fn, methods in handlers:
        if callable(add_api_route):
            app.add_api_route(path, fn, methods=methods, include_in_schema=False)
        elif _Route is not None:
            app.router.routes.append(_Route(path, fn, methods=methods))
    return [p for p, _, _ in handlers]


