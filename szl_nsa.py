def compress_branch(tokens: list, block_size: int) -> list:
    """Branch (a) — coarse COMPRESSION: mean-pool each contiguous block of
    `block_size` key/value token vectors into ONE summary vector. Returns the
    list of summary vectors (len = ceil(seq_len / block_size)). This is the
    NSA "compressed coarse-grained tokens" branch: O(seq_len) work total,
    O(seq_len / block_size) summary tokens attended per query."""
    if block_size < 1:
        raise ValueError("block_size must be >= 1")
    out = []
    n = len(tokens)
    for start in range(0, n, block_size):
        block = tokens[start:start + block_size]
        dim = len(block[0])
        summary = [sum(v[d] for v in block) / len(block) for d in range(dim)]
        out.append(summary)
    return out


def selection_branch(query: list, tokens: list, block_size: int, topk: int):
    """Branch (b) — blockwise TOP-K SELECTION, NSA-style two-stage scoring:

      Stage 1 (CHEAP proxy, O(n_blocks) evals): score each contiguous block
      by ONE dot-product of the query against the block's mean-pooled vector
      (cheap — reuses the same pooled representation as the compression
      branch's summary tokens as its importance proxy, per the NSA paper's
      blockwise-selection scoring).

      Stage 2 (FULL fine-grained attention, O(topk * block_size) evals): only
      the `topk` highest-proxy-scoring blocks are expanded to their raw
      per-token vectors and dot-producted individually against the query.

    Returns (selected_block_indices, proxy_scores, n_score_evals) where
    n_score_evals is the SUM of stage-1 + stage-2 evals actually performed
    (for the FLOPs accounting) — NOT a formula, an actual count."""
    n = len(tokens)
    block_starts = list(range(0, n, block_size))
    n_evals = 0

    # stage 1: cheap block-level proxy via mean-pooled vector (1 eval/block).
    proxy_scores = []
    for start in block_starts:
        block = tokens[start:start + block_size]
        dim = len(block[0])
        pooled = [sum(v[d] for v in block) / len(block) for d in range(dim)]
        proxy_scores.append(_dot(query, pooled))
        n_evals += 1

    ranked = sorted(range(len(block_starts)), key=lambda i: proxy_scores[i], reverse=True)
    chosen = sorted(ranked[:max(0, min(topk, len(block_starts)))])

    # stage 2: full fine-grained attention only on the CHOSEN blocks' raw tokens.
    fine_scores = {}
    for bi in chosen:
        start = block_starts[bi]
        block = tokens[start:start + block_size]
        s = 0.0
        for v in block:
            s += _dot(query, v)
            n_evals += 1
        fine_scores[bi] = s / len(block)

    # report the fine (stage-2) score where available, else the cheap proxy —
    # the fine score is what actually drives select_score in the caller.
    scores = [fine_scores.get(i, proxy_scores[i]) for i in range(len(block_starts))]
    return chosen, scores, n_evals


def sliding_window_branch(pos: int, seq_len: int, window: int) -> list:
    """Branch (c) — local SLIDING WINDOW: the `window` most-recent positions
    immediately preceding (and including) `pos`. Always-on local context,
    O(window) per query regardless of seq_len."""
    lo = max(0, pos - window + 1)
    return list(range(lo, pos + 1))


# Fixed (non-learned) gate weights — FIXED for determinism, per the NSA demo
# spec ("gate-combine with fixed scalar weights"). Sums to 1.0.
GATE_WEIGHTS = {"compression": 0.25, "selection": 0.50, "sliding_window": 0.25}


def gated_combine(compress_score: float, select_score: float, window_score: float) -> float:
    """Fixed-weight linear gate combination of the three branch outputs, per
    NSA eq. (gating network) but with FIXED (not learned) scalars so the
    result is fully deterministic."""
    w = GATE_WEIGHTS
    return (w["compression"] * compress_score
            + w["selection"] * select_score
            + w["sliding_window"] * window_score)


# ---------------------------------------------------------------------------
# DENSE REFERENCE — full O(L^2) attention proxy, for parity / FLOPs baseline.
# ---------------------------------------------------------------------------
def dense_reference_scores(query: list, tokens: list) -> list:
    """Every-position dot-product score (the dense/full-attention baseline)
    for ONE query against ALL seq_len keys. O(seq_len) evals for this one
    query, O(seq_len^2) for the whole sequence — the quadratic term NSA
    avoids."""
    return [_dot(query, v) for v in tokens]


def dense_topk_positions(scores: list, k: int) -> list:
    ranked = sorted(range(len(scores)), key=lambda i: scores[i], reverse=True)
    return sorted(ranked[:max(0, min(k, len(scores)))])


def nsa_selected_positions(sel_blocks: list, block_size: int, window_positions: list, n: int) -> list:
    """Union of the raw token positions covered by the selected blocks and the
    sliding-window branch (the compression branch contributes SUMMARY tokens,
    not raw positions, so it is excluded from this raw-position recall check
    by construction — it is accounted separately in FLOPs)."""
    positions = set(window_positions)
    for bi in sel_blocks:
        start = bi * block_size
        positions.update(range(start, min(start + block_size, n)))
    return sorted(positions)


