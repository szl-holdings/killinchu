# Deterministic LCG PRNG — pure stdlib, NO numpy, NO `random` module.
# Numerical-Recipes-style constants (Press et al.): full-period 32-bit LCG.
# Same seed -> byte-identical stream, forever, on any machine.
# ---------------------------------------------------------------------------
_LCG_A = 1664525
_LCG_C = 1013904223
_LCG_M = 2 ** 32


class _LCG:
    """Minimal deterministic linear-congruential generator.

    x_{n+1} = (A * x_n + C) mod 2**32.  `next_float()` maps the 32-bit state
    into [0, 1). Pure integer arithmetic — no external RNG source, no
    hardware entropy, fully reproducible from an integer seed.
    """

    __slots__ = ("state",)

    def __init__(self, seed: int):
        self.state = int(seed) & 0xFFFFFFFF

    def next_uint(self) -> int:
        self.state = (_LCG_A * self.state + _LCG_C) % _LCG_M
        return self.state

    def next_float(self) -> float:
        return self.next_uint() / float(_LCG_M)

    def next_signed(self) -> float:
        """Uniform in [-1, 1) — used to synthesize token feature vectors."""
        return self.next_float() * 2.0 - 1.0


def _make_token_vectors(rng: _LCG, seq_len: int, dim: int) -> list:
    """Synthesize `seq_len` deterministic token feature vectors of `dim`
    floats each, drawn from the LCG. Stands in for real hidden-state vectors
    so the branches below have something concrete (but synthetic) to score."""
    return [[rng.next_signed() for _ in range(dim)] for _ in range(seq_len)]


def _dot(a: list, b: list) -> float:
    return sum(ai * bi for ai, bi in zip(a, b))


