    canon_b = _canon(run_b)
    assert canon_a == canon_b, "same seed+config must yield byte-identical payload"
    assert _sha3(canon_a) == _sha3(canon_b)
    out["run_determinism_ok"] = True
    out["run_digest_seed42"] = _sha3(canon_a)

    # (c) different seed -> (almost certainly) different output.
    run_c = run_nsa_simulation(seed=7, seq_len=128, dim=8, block_size=16, topk=3, window=8)
    assert _canon(run_c) != canon_a, "different seeds should change the payload"
    out["seed_sensitivity_ok"] = True

    # (d) honesty label verbatim MODELED, never anything else.
    assert run_a["label"] == "MODELED"
    assert simulate_payload(seed=42, seq_len=64)["payload"]["label"] == "MODELED"
    out["label_verbatim_modeled_ok"] = True

    # (e) branch sanity: selection picks <= n_blocks, sliding window <= window
    # positions, compression yields ceil(L/block_size) summaries.
    assert run_a["branches"]["compression"]["n_summary_tokens"] == math.ceil(128 / 16)
    assert len(run_a["branches"]["selection"]["selected_block_indices"]) <= 3
    assert len(run_a["branches"]["sliding_window"]["window_positions"]) <= 8
    out["branch_shapes_ok"] = True

    # (f) sparsity: NSA's per-query eval count must be << dense for a longer seq.
    run_long = run_nsa_simulation(seed=42, seq_len=2048, dim=8, block_size=32, topk=4, window=32)
    fa = run_long["flops_accounting"]["this_query"]
    assert fa["nsa_evals"] < fa["dense_evals"], "NSA per-query evals must be sparser than dense"
    out["sparsity_ok"] = True
    out["sparsity_ratio_seq2048"] = fa["sparsity_ratio"]

    # (g) gate weights sum to 1 (fixed-weight combine is well-formed).
    assert abs(sum(GATE_WEIGHTS.values()) - 1.0) < 1e-12
    out["gate_weights_sum_to_1_ok"] = True

    # (h) parity/recall check produces a value in [0,1] when applicable.
    rec = run_a["parity_check"]["recall_vs_dense_oracle"]
    assert rec is None or (0.0 <= rec <= 1.0)
    out["parity_recall_in_range_ok"] = True

    out["all_passed"] = True
    return out


